// UI-only end-to-end test (no side-channel API calls, so it behaves like one judge in one tab).  B=https://tessera-guard.vercel.app node docs/tools/live-ui-test.mjs
import { chromium } from "/home/arch-nitro/d3coy/tessera-lab/web/node_modules/playwright-core/index.mjs";
const B = process.env.B || "https://tessera-guard.vercel.app";
const b = await chromium.launch({ executablePath: "/usr/bin/google-chrome-stable", args: ["--no-sandbox"] });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } }); const errs = []; p.on("pageerror", e => errs.push(e.message.slice(0, 140)));
let pass = 0, fail = 0; const ok = (n, c) => { c ? pass++ : fail++; console.log((c ? "PASS " : "FAIL ") + n); };
const has = async (re, t = 12000) => { try { await p.getByText(re).first().waitFor({ timeout: t }); return true; } catch { return false; } };
await p.goto(B + "/", { waitUntil: "networkidle" });
ok("landing shows headline", await has(/Wrong behaviour/));
ok("isometric machine blocks the poisoned PDF", await has(/1 blocked|hidden order blocked/, 15000));
await p.getByRole("link", { name: /Open the lab/ }).click(); await p.waitForURL(/\/fleet/);
await p.getByRole("link", { name: /Start here/ }).first().click(); await p.waitForURL(/\/guide/);
await p.getByRole("button", { name: /^Run the attack/ }).click(); await p.waitForURL(/\/demo/, { timeout: 20000 });
ok("demo: TESSERA blocks hidden-instruction steps", await has(/Blocked/, 25000));
ok("demo: 4 of 5 steps finished", await has(/4 of 5/, 25000));
await p.goto(B + "/fleet", { waitUntil: "networkidle" });
ok("fleet: attack stopped strip", await has(/Attack stopped/, 20000));
const appr = p.getByRole("button", { name: /^Approve/ }).first();
if (await appr.count()) { await appr.click(); ok("fleet: approve held action", await has(/Allowed/, 10000)); } else ok("fleet: approval card present", false);
await p.getByRole("link", { name: /^Cases/ }).first().click(); await p.waitForURL(/\/cases/);
await p.locator("a[href^='/cases/case_']").first().click(); await p.waitForURL(/\/cases\/case_/, { timeout: 15000 });
ok("case: shows hidden text on the document", await has(/Hidden text/, 15000));
ok("case: score breakdown", await has(/Outside the job description/, 15000));
const tam = p.getByRole("button", { name: /^Tamper/ }); await tam.waitFor({ timeout: 15000 }); await tam.click();
await p.getByRole("button", { name: /^Verify/ }).click();
ok("case: tampered receipt is detected", await has(/modified|broken|fail|tamper/i, 10000));
await p.goto(B + "/lab", { waitUntil: "networkidle" });
await p.getByText(/ACME Q4 quote \(page 3 poisoned\)/).first().click(); await p.getByRole("button", { name: /^Run$/ }).click();
ok("lab: poisoned quote stopped", await has(/Attack stopped/, 25000));
await p.goto(B + "/hijack", { waitUntil: "networkidle" });
await p.getByRole("button", { name: /Send as the agent/ }).click();
ok("hijack: access check allowed, TESSERA blocks", await has(/Blocked/, 15000));
await p.goto(B + "/chains", { waitUntil: "networkidle" });
await p.getByRole("button", { name: /Run chain attack/ }).click();
ok("chains: patient zero named", await has(/patient zero/i, 25000));
await p.goto(B + "/contracts", { waitUntil: "networkidle" });
ok("contracts: Cedar compiles", await has(/Valid|Compiles/, 15000));
await p.goto(B + "/bench", { waitUntil: "networkidle" });
ok("results: MEASURED tags", await has(/MEASURED/, 15000));
await p.goto(B + "/agents/agt_proc_01", { waitUntil: "networkidle" });
ok("agent: working-hours clock", await has(/Working-hours clock/, 15000));
console.log(`\n${pass} passed, ${fail} failed; page errors: ${errs.length}`, errs.slice(0, 3));
await b.close();
